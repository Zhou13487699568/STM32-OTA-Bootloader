/**
  * @brief This function handles USART1 global interrupt.
  */
void USART1_IRQHandler(void)
{
  /* USER CODE BEGIN USART1_IRQn 0 */
        if(__HAL_UART_GET_FLAG(&huart1,UART_FLAG_IDLE)!=RESET)
	{
		uint16_t recv_len;
		
		__HAL_UART_CLEAR_IDLEFLAG(&huart1);//手动清理DMA标志位
			HAL_UART_DMAStop(&huart1);//停止DMA
		
		recv_len = (uint16_t)(U0_RX_MAX+1-__HAL_DMA_GET_COUNTER(huart1.hdmarx));
		
		if(recv_len > 0)   /* 空闲中断被干扰触发、收到 0 字节时不能更新指针，
		                    * 否则 &U0_RxBuff[URxcounter-1] 会下标越界 */
		{
			U0CB.URxcounter += recv_len;//记录已用数据的字节大小
			U0CB.IN->end=&U0_RxBuff[U0CB.URxcounter-1];
			U0CB.IN++;
			if(U0CB.IN == U0CB.END)
			{
				U0CB.IN=&U0CB.URxDataPtr[0];//
			}

			/* 注意要和 DMA 长度 U0_RX_MAX+1 比较，用 U0_RX_MAX 会多写 1 字节越界 */
			if(U0_RX_SIZE-U0CB.URxcounter >= U0_RX_MAX+1 )
			{
				U0CB.IN->star=&U0_RxBuff[U0CB.URxcounter];
			}else{
				U0CB.IN->star=U0_RxBuff;
				U0CB.URxcounter=0;
			}
		}
		
		HAL_UART_Receive_DMA(&huart1,U0CB.IN->star,U0_RX_MAX+1);//重开DMA接收数据
	}
			
	
  /* USER CODE END USART1_IRQn 0 */
  HAL_UART_IRQHandler(&huart1);
  /* USER CODE BEGIN USART1_IRQn 1 */

	
  /* USER CODE END USART1_IRQn 1 */
}

